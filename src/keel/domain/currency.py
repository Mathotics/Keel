DEFAULT_CURRENCY = "USD"
_INVALID = "Currency must be an ISO code such as USD."


def normalize_currency(raw: str | None) -> str:
    """Return the uppercase ISO code, or refuse a blank or unknown one."""
    cleaned = (raw or "").strip().upper()
    if cleaned not in CODES:
        raise InvalidCurrencyError(_INVALID, value=raw or "")
    return cleaned


def display_places(code: str) -> int:
    """Usual decimal places on a read-only amount. Three and four stay at two."""
    exponent = MINOR_UNITS.get(code, 2)
    if exponent == 0:
        return 0
    return 2
